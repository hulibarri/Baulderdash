/* Draws an unused card. `used` is an array of "cat:index" strings (changed in place).
   Picks a category at random from `cats` (like rolling the die), unless forceCat is given. */
function drawFrom(used, cats, forceCat){
  const keys = (cats && cats.length ? cats : CAT_KEYS).filter(c => DECKS[c]);
  const cat = (forceCat && DECKS[forceCat]) ? forceCat : keys[Math.floor(Math.random() * keys.length)];
  const deck = DECKS[cat];
  let pool = deck.map((_, i) => i).filter(i => !used.includes(cat + ":" + i));
  if(!pool.length){
    for(let k = used.length - 1; k >= 0; k--) if(String(used[k]).startsWith(cat + ":")) used.splice(k, 1);
    pool = deck.map((_, i) => i);
  }
  const i = pool[Math.floor(Math.random() * pool.length)];
  used.push(cat + ":" + i);
  return { cat, word: deck[i][0], def: deck[i][1] };
}
